// programs/sim/gen-state.mjs
//
// Reads the live betanet accounts the graduation simulation starts from and
// writes them out as a C header, so sim.c runs the new programs against the
// exact bytes GIL and BNPROOF have on chain today. Read-only: it only calls
// the account read in api/rpc.js.
//
//   node programs/sim/gen-state.mjs <out.h>

import { writeFileSync } from 'node:fs'
import handler from '../../api/rpc.js'
import { decodePadRegistry } from '../../src/lib/pad.js'
import { Pubkey } from '@thru/sdk'
import { addressOf } from '../../src/lib/networks.js'

const call = (q) => new Promise((ok) => {
  const res = {
    statusCode: 200, setHeader() {}, status(c) { this.statusCode = c; return this },
    json(b) { ok(b); return this }, send(b) { ok(typeof b === 'string' ? JSON.parse(b) : b); return this }, end(b) { ok(b ? JSON.parse(b) : null) },
  }
  handler({ method: 'GET', query: q, url: '/', headers: {} }, res)
})

async function bytesOf(address) {
  const r = await call({ action: 'account', address })
  const b64 = (r.account ?? r)?.data?.base64
  if (!b64) throw new Error(`no data for ${address}: ${JSON.stringify(r).slice(0, 200)}`)
  return Buffer.from(b64, 'base64')
}

const key = (a) => Buffer.from(Pubkey.from(a).toBytes())
const arr = (name, buf) => `static uchar const ${name}[ ${buf.length} ] = {\n${[...buf].map((x) => `0x${x.toString(16).padStart(2, '0')}`).join(',').replace(/(([^,]*,){16})/g, '$1\n')}\n};\n`

const PAD_REGISTRY = addressOf('THRUPAD_REGISTRY')
const SWAP_REGISTRY = addressOf('THRUSWAP_REGISTRY')
const padReg = await bytesOf(PAD_REGISTRY)
const swapReg = await bytesOf(SWAP_REGISTRY)
const reg = decodePadRegistry(padReg.toString('base64'))

let out = `/* Generated by gen-state.mjs from betanet at ${new Date().toISOString()}. */\n\n`
out += arr('K_PAD_PROGRAM', key(addressOf('THRUPAD_PROGRAM')))
out += arr('K_SWAP_PROGRAM', key(addressOf('THRUSWAP_PROGRAM')))
out += arr('K_PAD_REGISTRY', key(PAD_REGISTRY))
out += arr('K_SWAP_REGISTRY', key(SWAP_REGISTRY))
out += arr('D_PAD_REGISTRY', padReg)
out += arr('D_SWAP_REGISTRY', swapReg)

for (const sym of ['GIL', 'BNPROOF']) {
  const l = reg.launches.find((x) => x.symbol.toUpperCase() === sym)
  if (!l) throw new Error(`${sym} not in the registry`)
  out += `#define ${sym}_ID (${l.id})\n`
  for (const [name, address] of [['TOKEN_VAULT', l.tokenVault], ['QUOTE_VAULT', l.quoteVault], ['MINT', l.mint], ['QUOTE_MINT', l.quoteMint]]) {
    out += arr(`K_${sym}_${name}`, key(address))
    out += arr(`D_${sym}_${name}`, await bytesOf(address))
  }
}
writeFileSync(process.argv[2], out)
console.log(`wrote ${process.argv[2]}: pad registry ${padReg.length} bytes, swap registry ${swapReg.length} bytes, threshold ${reg.gradThreshold}`)
process.exit(0)
